(function () {
    'use strict';

    /**
     * Shows the custom alert bar with a message.
     * Auto-hides after 5 seconds.
     * @param {string} message
     */
    function showAlert(message) {
        var alertBox = document.getElementById('customAlert');
        if (!alertBox) return;

        alertBox.textContent = message;
        alertBox.style.display = 'block';

        if (alertBox._alertTimer) {
            clearTimeout(alertBox._alertTimer);
        }
        alertBox._alertTimer = setTimeout(function () {
            alertBox.style.display = 'none';
        }, 5000);
    }

    /**
     * Hides the custom alert bar.
     */
    function hideAlert() {
        var alertBox = document.getElementById('customAlert');
        if (!alertBox) return;

        alertBox.style.display = 'none';
        if (alertBox._alertTimer) {
            clearTimeout(alertBox._alertTimer);
        }
    }

    /**
     * Shows the result container with the shortened link details.
     * @param {{ shortenedLink: string, shortenerLinkId: number }} data
     */
    function showResult(data) {
        var form = document.getElementById('shortenerForm');
        var resultContainer = document.getElementById('resultContainer');
        var loginPrompt = document.getElementById('loginPromptContainer');
        var shortLinkInput = document.getElementById('shortLinkInput');
        var qrCodeLinkId = document.getElementById('qrCodeLinkId');
        var analyticsLink = document.getElementById('analyticsLink');

        if (!resultContainer || !shortLinkInput) return;

        // Populate the shortened link
        shortLinkInput.value = data.shortenedLink || '';

        // Build dashboard links with the link id
        var linkId = data.shortenerLinkId;
        if (qrCodeLinkId && linkId) {
            qrCodeLinkId.value = linkId;
        }
        if (analyticsLink && linkId) {
            analyticsLink.href = '/Home/LinkAnalytics?linkId=' + linkId;
        }

        // Hide form, hide login prompt, show result
        if (form) form.style.display = 'none';
        if (loginPrompt) loginPrompt.classList.add('hidden');
        resultContainer.classList.remove('hidden');

        // Scroll to result
        resultContainer.scrollIntoView({ behavior: 'instant', block: 'nearest' });
    }

    /**
     * Shows the login-required prompt card.
     */
    function showLoginRequired() {
        var form = document.getElementById('shortenerForm');
        var resultContainer = document.getElementById('resultContainer');
        var loginPrompt = document.getElementById('loginPromptContainer');

        // Hide form and result, show login prompt
        if (form) form.style.display = 'none';
        if (resultContainer) resultContainer.classList.add('hidden');
        if (loginPrompt) {
            loginPrompt.classList.remove('hidden');
            loginPrompt.scrollIntoView({ behavior: 'instant', block: 'nearest' });
        }
    }

    /**
     * Resets the shortener to its initial state (form visible, results hidden).
     */
    function resetShortener() {
        var form = document.getElementById('shortenerForm');
        var resultContainer = document.getElementById('resultContainer');
        var loginPrompt = document.getElementById('loginPromptContainer');
        var urlInput = document.getElementById('url-input');

        // Reset form fields
        if (form) form.reset();
        if (urlInput) urlInput.value = '';

        // Clear hidden inputs
        var hiddenInputs = form ? form.querySelectorAll('input[type="hidden"]') : [];
        for (var i = 0; i < hiddenInputs.length; i++) {
            hiddenInputs[i].value = '';
        }

        // Hide result and login prompt
        if (resultContainer) resultContainer.classList.add('hidden');
        if (loginPrompt) loginPrompt.classList.add('hidden');

        // Show form
        if (form) form.style.display = 'block';

        // Focus on input
        if (urlInput) urlInput.focus();
    }

    /**
     * Reads the antiforgery token value from the hidden input
     * generated by @Html.AntiForgeryToken() / asp-action tag helper.
     * @returns {string|null}
     */
    function getAntiForgeryToken() {
        var input = document.querySelector('input[name="__RequestVerificationToken"]');
        return input ? input.value : null;
    }

    /**
     * Simple form-level valid check — replicates what validateTextField does
     * so the capture handler can decide whether to stop propagation.
     * Only checks the URL input field.
     * @returns {boolean} true if the form appears valid enough to proceed
     */
    function isFormBasicallyValid() {
        var urlInput = document.getElementById('url-input');
        if (!urlInput) return false;

        var value = urlInput.value.trim();
        if (!value) return false;

        // Try the raw value first
        try {
            var url = new URL(value);
            if (url.protocol === 'http:' || url.protocol === 'https:') return true;
        } catch (_) {
            // Not a valid absolute URL — fall through
        }

        // Try with https:// prefix (matches server-side normalization)
        try {
            var url = new URL('https://' + value);
            return url.protocol === 'http:' || url.protocol === 'https:';
        } catch (_) {
            return false;
        }
    }

    /**
     * Enables loading state on the submit button (matches original startSubmitLoading).
     */
    function enableSubmitLoading(btn) {
        if (!btn) return;
        btn.dataset.pvOriginalDisabled = btn.disabled ? 'true' : 'false';
        btn.disabled = true;
        btn.classList.add('pv-submit-loading');
    }

    /**
     * Disables loading state on the submit button (matches original stopSubmitLoading).
     */
    function disableSubmitLoading(btn) {
        if (!btn) return;
        btn.disabled = btn.dataset.pvOriginalDisabled === 'true';
        btn.classList.remove('pv-submit-loading');
    }

    // ---- Initialisation ----
    document.addEventListener('DOMContentLoaded', function () {
        var form = document.getElementById('shortenerForm');
        if (!form) return;

        // Prevent double-binding
        if (form.dataset.pvAjaxReady === 'true') return;
        form.dataset.pvAjaxReady = 'true';

        var submitBtn = form.querySelector('.shorten-btn');

        // Ensure result and login-prompt are hidden on initial page load
        var resultContainer = document.getElementById('resultContainer');
        var loginPrompt = document.getElementById('loginPromptContainer');
        if (resultContainer) resultContainer.classList.add('hidden');
        if (loginPrompt) loginPrompt.classList.add('hidden');

        // ---- Intercept form submission (capture phase, fires BEFORE validation system's handler) ----
        form.addEventListener('submit', async function (event) {
            // If the validation system already set pvSubmitting, stop the native submit
            if (form.dataset.pvSubmitting === 'true') {
                event.preventDefault();
                event.stopPropagation();
                return;
            }

            hideAlert();

            // If the form is NOT valid, let the validation system's handler
            // (added by payvand-validation.js via data-pv-validate) run normally.
            // It will validate, show field errors (red borders + messages),
            // show form-level error, and NOT submit.
            if (!isFormBasicallyValid()) {
                return;  // Let validation handler process the invalid form
            }

            // ---- Form is valid — proceed with AJAX ----

            // Stop event propagation so the validation system's submit handler
            // does NOT fire. Without this, it would call
            // HTMLFormElement.prototype.submit.call(form) which does a native POST.
            event.stopPropagation();
            event.preventDefault();

            // Set the same flag the validation system checks — if it somehow still
            // receives this event, it will bail at the top: if (form.dataset.pvSubmitting === 'true') return;
            form.dataset.pvSubmitting = 'true';

            // --- Restore original loading experience ---
            // 1. Show the PayvandLoader global overlay (chain-link animation)
            if (window.PayvandLoader) {
                PayvandLoader.show('Shortening your link...');
            }
            // 2. Enable button loading state (original pv-submit-loading class)
            enableSubmitLoading(submitBtn);

            try {
                // Build form data (includes the anti-forgery token from the hidden input)
                var formData = new FormData(form);
                var urlInput = document.getElementById('url-input');
                var url = urlInput ? urlInput.value.trim() : '';
                // Ensure OriginalUrl is set correctly
                formData.set('OriginalUrl', url);

                var response = await fetch('/Home/LinkShortener', {
                    method: 'POST',
                    headers: {
                        'X-Requested-With': 'XMLHttpRequest',
                        'RequestVerificationToken': getAntiForgeryToken() || ''
                    },
                    body: formData
                });

                if (!response.ok) {
                    if (response.status === 400 || response.status === 422) {
                        showAlert('Security check failed. Reload the page and try again.');
                    } else {
                        showAlert('Could not process the request. Please try again.');
                    }
                    return;
                }

                var data = await response.json();

                // Normalize property names — handle both camelCase (System.Text.Json)
                // and PascalCase (Newtonsoft.Json) serialization
                var normalizedData = {
                    shortenedLink: data.shortenedLink || data.ShortenedLink || '',
                    shortenerLinkId: data.shortenerLinkId || data.ShortenerLinkId,
                    loginRequired: data.loginRequired === true || data.LoginRequired === true,
                    success: data.success === true || data.Success === true,
                    message: data.message || data.Message || ''
                };

                if (normalizedData.loginRequired) {
                    showLoginRequired();
                } else if (normalizedData.success) {
                    showResult(normalizedData);
                } else {
                    showAlert(normalizedData.message || 'Something went wrong. Please try again.');
                }
            } catch (error) {
                showAlert('Could not reach the server. Check your connection.');
            } finally {
                // Hide loading — matches original stopSubmitLoading
                if (window.PayvandLoader) {
                    PayvandLoader.hide();
                }
                disableSubmitLoading(submitBtn);
                // Reset the flag so the form can be submitted again
                form.dataset.pvSubmitting = 'false';
            }
        }, true); // capture phase — fires before the validation system's bubbling handler

        // ---- Copy to clipboard ----
        var copyBtn = document.getElementById('copyBtn');
        if (copyBtn) {
            copyBtn.addEventListener('click', function () {
                var input = document.getElementById('shortLinkInput');
                if (!input) return;

                input.select();
                input.setSelectionRange(0, 99999);

                navigator.clipboard.writeText(input.value).then(function () {
                    copyBtn.textContent = 'Copied!';
                    copyBtn.classList.add('copied');

                    setTimeout(function () {
                        copyBtn.textContent = 'Copy';
                        copyBtn.classList.remove('copied');
                    }, 2000);
                }).catch(function () {
                    // Fallback: select only
                    showAlert('Automatic copy failed. Copy the link manually.');
                });
            });
        }

        // ---- New Shorten button ----
        var newShortenBtn = document.getElementById('newShortenBtn');
        if (newShortenBtn) {
            newShortenBtn.addEventListener('click', resetShortener);
        }
    });
})();
